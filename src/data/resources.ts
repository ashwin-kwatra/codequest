// Flat lookup map by topicId
export const TOPIC_RESOURCES_MAP: Record<string, CuratedResource[]> = {};
for (const res of CURATED_RESOURCES) {
  if (!TOPIC_RESOURCES_MAP[res.topicId]) {
    TOPIC_RESOURCES_MAP[res.topicId] = [];
  }
  TOPIC_RESOURCES_MAP[res.topicId].push(res);
}

export function getResourcesForTopic(topicId: string): CuratedResource[] {
  return TOPIC_RESOURCES_MAP[topicId] || [];
}

export function getPrimaryResourceForTopic(topicId: string): CuratedResource | undefined {
  const list = TOPIC_RESOURCES_MAP[topicId] || [];
  return list.find(r => r.isPrimary) || list[0];
}
